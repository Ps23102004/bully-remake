#!/usr/bin/env python3
"""Builds Config/Missions/day_one.json (the one-file playthrough) from 1_01.json + 1_02.json.

The mission framework has no start_mission action yet, so a mission cannot chain into the next one from data. The combined
mission is simply the stage lists concatenated (1_01's mission-level on_complete moves onto its last stage), so the
game can boot into a continuous Day One with:  -BRMission=day_one   (or  Mission.Start day_one).
Re-run after editing 1_01.json / 1_02.json:  python3 Config/Missions/verify/build_day_one.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MISSIONS = os.path.dirname(HERE)


def load(name):
    with open(os.path.join(MISSIONS, name + ".json")) as f:
        return json.load(f)


a, b = load("1_01"), load("1_02")
points = dict(a.get("points", {}))
for k, v in b.get("points", {}).items():
    assert k not in points or points[k] == v, "point %s differs between 1_01 and 1_02" % k
    points[k] = v
triggers = {t["id"]: t for t in a.get("triggers", [])}
for t in b.get("triggers", []):
    assert t["id"] not in triggers or triggers[t["id"]] == t, "trigger %s differs" % t["id"]
    triggers[t["id"]] = t
stages = a["stages"] + b["stages"]
ids = [s["id"] for s in stages]
assert len(ids) == len(set(ids)), "duplicate stage ids"
stages[len(a["stages"]) - 1].setdefault("on_complete", []).extend(a.get("on_complete", []))
out = {
    "_format": "bully-remake.mission/1",
    "_note": "GENERATED by Config/Missions/verify/build_day_one.py from 1_01.json + 1_02.json (edit those, then re-run). One continuous Day One: arrive, gauntlet, office, briefing, dorm court tutorial fight, dorm door, end card. Boot into it with -BRMission=day_one or Mission.Start day_one. Stage ids are unique across both halves.",
    "id": "day_one",
    "title": "Day One",
    "retry": "stage",
    "fail_delay": b.get("fail_delay", 3.0),
    "start": a["start"],
    "points": points,
    "triggers": list(triggers.values()),
    "stages": stages,
    "on_complete": b.get("on_complete", []),
}
path = os.path.join(MISSIONS, "day_one.json")
with open(path, "w") as f:
    json.dump(out, f, indent=2)
    f.write("\n")
print("wrote %s: %d stages (%d + %d), %d points, %d triggers" % (path, len(stages), len(a["stages"]), len(b["stages"]), len(points), len(triggers)))
