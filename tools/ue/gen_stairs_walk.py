#!/usr/bin/env python3
# OWNER: slice-stairs
"""Make a walk-runner script (tools/ue/run_walk_nullrhi.sh --script ...) that drives the REAL pawn along the path the
capsule-sweep probe (stairs_probe.py) found: lobby door exit -> stairs -> landing -> upper floor -> office point.

  python3 tools/ue/gen_stairs_walk.py PROBE.json OUT.json [--every N] [--gait walk|run] [--radius CM]

Waypoints are every Nth path node (default 6, ~1.5 m) plus the last one. After each waypoint a `log` step records the pawn
position (z shows the climb). The last step is `walk_to` the office trigger point; `log` 'office_arrived' closes the run.
"""
import argparse
import json


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("probe")
    ap.add_argument("out")
    ap.add_argument("--every", type=int, default=6)
    ap.add_argument("--gait", default="run")
    ap.add_argument("--radius", type=float, default=45.0)
    ap.add_argument("--full", action="store_true",
                    help="start at the front gates (PlayerStart), walk the courtyard, take the door link, climb to the office, "
                         "then walk back down and out through the lobby door (the whole 1_01 route and back)")
    a = ap.parse_args()
    r = json.load(open(a.probe))
    path = r.get("path") or r.get("path_to_highest")
    pts = path[::a.every]
    if pts[-1] != path[-1]:
        pts.append(path[-1])
    tgt = r.get("target")
    if tgt:   # finish exactly on the goal point (the probe stops within 60 cm of it)
        pts.append([tgt[0], tgt[1], tgt[2]])
    s0 = path[0]
    if a.full:
        steps = [
            {"do": "log", "name": "spawn"},
            {"do": "walk_to", "name": "gates_to_courtyard", "x": 21320, "y": 7330, "gait": "run", "timeout": 70, "radius": 60,
             "stop_on_door": False},
            {"do": "walk_to", "name": "into_main_door", "x": 21070, "y": 7330, "gait": "walk", "timeout": 20, "radius": 20},
            {"do": "wait_door", "timeout": 6},
            {"do": "wait", "seconds": 1.5},
            {"do": "log", "name": "lobby_start"},
        ]
    else:
        steps = [
            {"do": "log", "name": "spawn"},
            {"do": "teleport", "name": "to_lobby_door_exit", "x": s0[0], "y": s0[1], "z": s0[2] + 100, "yaw": -90},
            {"do": "wait", "seconds": 1.5},
            {"do": "log", "name": "lobby_start"},
        ]
    for i, p in enumerate(pts[1:], 1):
        steps.append({"do": "walk_to", "name": "wp%02d_z%.0f" % (i, p[2]), "x": round(p[0]), "y": round(p[1]),
                      "gait": a.gait, "timeout": 12, "radius": a.radius, "stop_on_door": False})
        steps.append({"do": "log", "name": "after_wp%02d" % i})
    steps.append({"do": "log", "name": "office_arrived"})
    if a.full:
        for i, p in enumerate(reversed(pts[:-1]), 1):
            steps.append({"do": "walk_to", "name": "down%02d_z%.0f" % (i, p[2]), "x": round(p[0]), "y": round(p[1]),
                          "gait": a.gait, "timeout": 12, "radius": a.radius, "stop_on_door": False})
        steps.append({"do": "log", "name": "back_in_lobby"})
        steps.append({"do": "walk_to", "name": "lobby_to_door", "x": -62860, "y": 32950, "gait": "run", "timeout": 40, "radius": 20})
        steps.append({"do": "wait_door", "timeout": 6})
        steps.append({"do": "log", "name": "back_outside"})
    out = {"_owner": "slice-stairs", "_note": "generated by gen_stairs_walk.py from " + a.probe,
           "warmup_seconds": 5, "settle_seconds": 1, "max_compile_wait_seconds": 1800, "exec": [], "steps": steps}
    json.dump(out, open(a.out, "w"), indent=1)
    print("wrote %s: %d waypoints" % (a.out, len(pts) - 1))


main()
